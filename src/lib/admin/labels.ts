/** Libellés qui dépendent de la nature de la valeur (section, liste ou simple champ). */
const kindLabels: Record<string, string> = {
  'cta:field': 'Texte du bouton',
  'services:list': 'Choix de services',
  'name:field': 'Nom',
  'stages:list': 'Étapes',
  'gallery:list': 'Galerie',
}

export function labelFor(key: string, kind: 'section' | 'list' | 'field' = 'field'): string {
  return kindLabels[`${key}:${kind}`] ?? labels[key] ?? key.replace(/([A-Z])/g, ' $1').replace(/^./, (c) => c.toUpperCase())
}

export function hintFor(path: string, key: string): string | undefined {
  return hints[path] || hints[key] || undefined
}
