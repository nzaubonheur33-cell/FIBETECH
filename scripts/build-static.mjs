import { cpSync, existsSync, mkdirSync, rmSync, symlinkSync, writeFileSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { join, resolve, sep } from 'node:path'

const root = process.cwd()
const workRoot = join(root, '.static-export-build')
const output = join(root, 'out')
const workMarker = join(workRoot, '.fibetech-static-build')
const outputMarker = join(output, '.fibetech-static-output')

function ensureGeneratedPath(path, marker) {
  const absolute = resolve(path)
  const rootAbsolute = resolve(root)
  if (!absolute.startsWith(`${rootAbsolute}${sep}`)) throw new Error(`Unsafe generated path: ${absolute}`)
  if (existsSync(path) && !existsSync(marker)) {
    throw new Error(`Refusing to overwrite an existing directory without a Fibetech build marker: ${path}`)
  }
}

ensureGeneratedPath(workRoot, workMarker)
ensureGeneratedPath(output, outputMarker)

for (const path of [workRoot, output]) {
  if (existsSync(path)) rmSync(path, { recursive: true, force: true })
}

mkdirSync(workRoot, { recursive: true })
writeFileSync(workMarker, 'Generated by scripts/build-static.mjs\n')

for (const relativePath of [
  'src',
  'public',
  'prisma',
  'package.json',
  'package-lock.json',
  'next.config.ts',
  'postcss.config.mjs',
  'tailwind.config.ts',
  'tsconfig.json',
  'next-env.d.ts',
]) {
  const source = join(root, relativePath)
  if (existsSync(source)) cpSync(source, join(workRoot, relativePath), { recursive: true })
}

const appRoot = join(workRoot, 'src', 'app')
for (const routeDirectory of ['api', 'admin', 'uploads']) {
  const excludedRoute = join(appRoot, routeDirectory)
  if (existsSync(excludedRoute)) rmSync(excludedRoute, { recursive: true, force: true })
}

const dependencies = join(root, 'node_modules')
if (!existsSync(dependencies)) throw new Error('Install dependencies before building the static frontend.')
symlinkSync(dependencies, join(workRoot, 'node_modules'), process.platform === 'win32' ? 'junction' : 'dir')

const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm'
const result = spawnSync(npm, ['run', 'build'], {
  cwd: workRoot,
  env: { ...process.env, FIBETECH_STATIC_FRONTEND: '1', NEXT_PUBLIC_FIBETECH_STATIC: '1' },
  shell: process.platform === 'win32',
  stdio: 'inherit',
})

if (result.error) throw result.error
if (result.status !== 0) process.exit(result.status ?? 1)

const generatedOutput = join(workRoot, 'out')
if (!existsSync(generatedOutput)) throw new Error('Next.js did not create the static out directory.')
cpSync(generatedOutput, output, { recursive: true })
writeFileSync(outputMarker, 'Generated by scripts/build-static.mjs\n')
rmSync(workRoot, { recursive: true, force: true })
console.log('Static frontend is ready in ./out')
